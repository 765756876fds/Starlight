def state(**changes):
    row = {
        "music": "playing",
        "movie": "stopped",
        "focus": "music",
        "page": "music",
        "recent_pause": "none",
        "queue_count": 20,
        "recommendation_session": True,
        "music_id": "synthetic-track-1",
        "movie_id": "synthetic-work-1",
        "kind": "movie",
        "preferred_kind": "movie",
        "stale": False,
        "candidate_ids": [],
        "playable_ids": [],
        "previous_candidate_id": None,
        "history": [],
        "liked_playlist_exists": True,
    }
    row.update(changes)
    return row


