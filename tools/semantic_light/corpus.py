def plan(*actions, **params):
    return decision(actions, params)


def ask():
    return decision(disposition="clarify")


def feedback(domain, rating="negative"):
    weak = {
        "domain": domain,
        "rating": rating,
        "strength": "weak",
        "item_id": f"synthetic-{'track' if domain == 'music' else 'work'}-1",
    }
    return decision(
        ["music.next"] if domain == "music" else ["movie.stop", "movie.recommend"],
        {} if domain == "music" else {"kind": "movie", "preserve_progress": True},
        weak,
    )


def positive(save=False, create=False):
    actions = ["music.recommendation_feedback"]
    params = {"feedback": "positive", "item_id": "synthetic-track-1"}
    if save:
        params["name"] = "我喜欢的音乐"
        actions += (["music.create_playlist"] if create else []) + ["music.add_to_playlist"]
    return decision(actions, params)


