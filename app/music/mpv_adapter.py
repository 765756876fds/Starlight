"""
MpvAdapter —— 播放器依赖协议（Protocol）

MusicController 不直接强依赖具体的 MpvController 类，而是依赖本协议。
测试可注入"不发真声音"的 Fake 对象（见 tests/unit/test_music.py 的
FakeMpvAdapter），提升测试稳定性与速度。

方法面 = controller.py 中 self.mpv.xxx 的全部实际调用（含 _properties
私有属性缓存，controller 在 pause/播放后会同步该字段）。
"""
from typing import Any, Callable, Optional, Protocol


class MpvAdapter(Protocol):
    """mpv 播放器最小协议（MusicController 实际调用面）。"""

    # ---- 生命周期 ----
    def start(self, taskkill: bool = True, pipe_timeout: float = 3.0,
              prop_timeout: float = 0.5) -> bool: ...
    def stop(self) -> None: ...
    def stop_process(self) -> None: ...
    def is_running(self) -> bool: ...

    # ---- 播放控制 ----
    def loadfile(self, filepath: str, mode: str = "replace") -> None: ...
    def play(self) -> None: ...
    def pause(self) -> None: ...
    def toggle_pause(self) -> None: ...
    def seek(self, seconds: float, mode: str = "relative") -> None: ...

    # ---- 状态查询 ----
    def get_property(self, name: str, timeout: float = 2.0) -> Any: ...
    def set_property(self, name: str, value: Any) -> None: ...
    def get_live_playback_time(self) -> float: ...
    def get_duration(self) -> float: ...
    def get_current_time(self) -> float: ...
    def get_volume(self) -> int: ...
    def set_volume(self, volume: int) -> None: ...
    def is_idle(self) -> bool: ...
    def is_paused(self) -> bool: ...
    def get_filename(self) -> Optional[str]: ...

    # ---- 事件订阅 ----
    def on_property_change(self, name: str, callback: Callable) -> None: ...

    # ---- 属性缓存（controller 在暂停/播放后会同步 _properties["pause"]）----
    _properties: dict
