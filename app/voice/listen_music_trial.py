"""Explicit isolated trial; no registration, persistent flag, or legacy retry.

The existing command worker owns the bounded run. Permits in command history
hold only a weak reference and generation, never text or player resources.
"""

from dataclasses import dataclass, field
import logging
import threading
import uuid
import weakref

from app.core.operation_result import OperationResult, OperationStatus as S
from app.music.goal_adapter import AdapterResult

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class TrialState:
    enabled: bool
    active: bool
    protected: bool
    route: str
    operation_id: str
    plan: str
    receipt: str
    collection_authorized: bool


@dataclass(frozen=True)
class TrialPermit:
    owner: weakref.ReferenceType = field(repr=False, compare=False)
    generation: int
    trace_id: str = ""


@dataclass(frozen=True)
class TrialResult(OperationResult):
    outcome: AdapterResult | None = field(default=None, repr=False)


class ListenMusicTrial:
    """Install explicitly on one runtime/controller; disabled by default.

    Closing the entry cancels its ticket, not already-issued IPC. Pending B4
    ownership stays in the same adapter even across enable/disable cycles.
    """

    PLANS = frozenset(("NO_OP", "RESUME_MUSIC", "TRY_COLLECTION"))

    def __init__(self, adapter, *, prepare_context=None):
        self.adapter = adapter
        self._prepare_context = prepare_context
        self._lock = threading.Lock()
        self._enabled = False
        self._generation = 0
        self._active = False
        self._ticket = None
        self._consumed = None
        self._legacy_unresolved = False
        self._listener = None
        self._trace_id, self._route = "", "V1"
        self._plan, self._receipt_status = "NONE", "IDLE"

    def snapshot(self):
        # Metadata only. No SQL, IPC, filesystem or worker wait on the GUI.
        with self._lock:
            values = (self._enabled, self._active, self._legacy_unresolved,
                      self._route, self._trace_id, self._plan, self._receipt_status)
        return TrialState(values[0], values[1], values[2] or self.adapter.unresolved,
                          *values[3:], self.adapter.resources.collection_authorized)

    def set_listener(self, listener):
        with self._lock:
            self._listener = listener
        self._announce()

    def _announce(self):
        state = self.snapshot()
        with self._lock:
            listener = self._listener
        if listener is not None:
            try:
                listener(state)  # GUI subscribers must enqueue, never update widgets here.
            except Exception:
                logger.warning("[ListenMusicTrial] status_delivery_unavailable")

    def _trace(self, operation_id, *, route=None, plan=None, receipt=None):
        with self._lock:
            if operation_id != self._trace_id:
                return  # Late results cannot replace a newer request's display.
            if route is not None:
                self._route = route
            if plan is not None:
                self._plan = plan
            if receipt is not None:
                self._receipt_status = receipt
            fields = (self._trace_id, self._route, self._plan, self._receipt_status)
        logger.info("[ListenMusicTrial] operation=%s route=%s plan=%s receipt=%s", *fields)
        self._announce()

    def note_legacy_result(self, command, result):
        with self._lock:
            relevant = command.notification_id == self._trace_id and self._route == "V1"
        if relevant:
            status = result.status.value if isinstance(result, OperationResult) else "unknown"
            self._trace(command.notification_id, receipt=status)

    def set_enabled(self, enabled):
        if type(enabled) is not bool:
            raise TypeError("trial flag must be bool")
        with self._lock:
            if enabled != self._enabled:
                self._generation += 1
                self._enabled = enabled
                if self._ticket is not None:
                    self._ticket.cancel.set()
            draining = self._active
        self._announce()
        return OperationResult(
            S.ACCEPTED if draining else S.CONFIRMED,
            "入口已调整，上一请求正在收尾" if draining else "试验入口已开启" if enabled else "试验入口已关闭",
        )

    def voice_advanced(self):
        with self._lock:
            self._generation += 1
            if self._ticket is not None:
                self._ticket.cancel.set()

    def permit(self, text, params, operation_id=None):
        # Restrict the already-parsed intent. This does not expand recognition.
        if params or text.strip().rstrip("。.!！") != "我想听歌了":
            return None
        # Operation identifiers are generated by the notification center. Never
        # accept arbitrary user text as a log identifier.
        trace_id = str(operation_id or "")
        if not trace_id or len(trace_id) > 96 or any(not (ch.isascii() and (ch.isalnum() or ch in "-_:.")) for ch in trace_id):
            trace_id = uuid.uuid4().hex
        with self._lock:
            legacy = (not self._enabled and not self._active and not self._legacy_unresolved
                      and not self.adapter.unresolved)
            self._trace_id = trace_id
            permit = None if legacy else TrialPermit(weakref.ref(self), self._generation, trace_id)
        self._trace(trace_id, route="V1" if legacy else "B5", plan="LEGACY_RECOMMEND" if legacy else "NONE", receipt="DISPATCHED")
        return permit

    def handle(self, command):
        if command.goal_trial is None:
            return None
        permit = command.goal_trial
        trace_id = permit.trace_id if isinstance(permit, TrialPermit) else ""
        self._trace(trace_id, receipt="DECIDING")
        result = self._handle(command)
        outcome = getattr(result, "outcome", None)
        status = (outcome.status if outcome is not None else
                  result.status.value if isinstance(result, OperationResult) else "unknown")
        self._trace(trace_id, receipt=status)
        return result

    def _handle(self, command):
        permit = command.goal_trial
        with self._lock:
            if permit is None:
                # Nontrial commands remain authoritative V1 requests, even
                # during drain. Their existing controller guards supersede us.
                return None
            if (
                not isinstance(permit, TrialPermit)
                or permit.owner() is not self
                or permit.generation != self._generation
                or command.source != "voice"
                or command.params
                or (command.is_current is not None and not command.is_current())
            ):
                return TrialResult(S.UNKNOWN, "请求已过期，未重新发起播放")
            if not self._enabled:
                return TrialResult(S.UNKNOWN, "试验入口已关闭；上次请求尚未收尾，未重复发起播放")
            if self._active:
                return TrialResult(S.UNKNOWN, "上一播放请求正在收尾，请稍后重试")
            if self._legacy_unresolved:
                return TrialResult(S.UNKNOWN, "上次播放结果仍未确认，未发起新的播放")
            if self._consumed == permit.generation:
                return TrialResult(S.UNKNOWN, "这次请求已经处理，未重复播放")
            self._consumed = permit.generation
            self._active = True
            self._ticket = self.adapter.begin()
            ticket = self._ticket
        legacy_selected = False
        try:
            if self._prepare_context is not None:
                self._prepare_context()  # Existing command worker, never the switch's GUI slot.
            prepared = self.adapter.prepare(ticket)
            if isinstance(prepared, AdapterResult):
                return self._feedback(prepared)
            decision, evidence = prepared.decision, prepared.resources
            self._trace(permit.trace_id, plan=decision.plan or "NONE", receipt="PREPARED")
            if decision.plan == "TRY_CHART":
                local = [c for c in evidence.candidates if c.plan == "TRY_COLLECTION"]
                if (not evidence.reliable or not evidence.collection_complete
                        or any(c.availability == "unknown" for c in local)
                        or any(c.availability == "attemptable" and c.explicit_match and not c.excluded for c in local)):
                    return TrialResult(S.UNKNOWN, "收藏资料尚不明确，未改变播放")
                self.adapter.validate_prepared(ticket, prepared)
                # This is the sole route choice, before execute/admit. Never
                # inspect a B4 failure and then call the old recommender.
                with self._lock:
                    if not self._enabled or permit.generation != self._generation or ticket.cancel.is_set():
                        return TrialResult(S.UNKNOWN, "请求已过期，未发起推荐")
                legacy_selected = True
                self._trace(permit.trace_id, route="V1_PRE_ADMISSION", receipt="NOT_ADMITTED")
                value = self.adapter.c.recommend_music_guarded_route(
                    prepared.state, ticket.cancel, command.is_current, evidence.database_revision
                )
                if not isinstance(value, OperationResult) or value.status not in (S.CONFIRMED, S.UNAVAILABLE):
                    with self._lock:
                        self._legacy_unresolved = True
                return value if isinstance(value, OperationResult) else TrialResult(S.UNKNOWN, "暂时无法确认推荐结果")
            if decision.plan == "TRY_COLLECTION" and not any(
                c.plan == "TRY_COLLECTION" and c.member == decision.member
                and c.availability == "attemptable" and c.explicit_match and not c.excluded
                for c in evidence.candidates
            ):
                return TrialResult(S.UNKNOWN, "没有足够的收藏偏好依据，未改变播放")
            result = self.adapter.run(ticket, budget=3, allowed_plans=self.PLANS, prepared=prepared)
            # A completed old command must not be presented as the new command.
            if command.is_current is not None and not command.is_current():
                return TrialResult(S.UNKNOWN, "请求已被新操作替代，未重新发起播放", result)
            return self._feedback(result)
        except Exception:
            if legacy_selected:
                with self._lock:
                    self._legacy_unresolved = True
            # Once admitted, an exception cannot prove absence of effects.
            return TrialResult(S.UNKNOWN, "暂时无法确认播放结果，请查看播放器")
        finally:
            with self._lock:
                self._active = False

    @staticmethod
    def _feedback(result):
        receipt = result.receipt
        if result.status == "started" and receipt is not None and receipt.proof is not None:
            return TrialResult(S.CONFIRMED, "已确认音乐正在播放", result)
        if result.status == "accepted":
            return TrialResult(S.ACCEPTED, "已受理播放请求，尚未确认起播", result)
        if result.status == "failed_no_effect":
            return TrialResult(S.FAILED, "未能开始播放，没有重新发起推荐", result)
        if result.status == "needs_clarification":
            return TrialResult(S.NEEDS_PARAMETER, "当前媒体状态不明确，未改变播放", result)
        if result.status in ("unavailable", "rejected_unavailable", "disabled"):
            return TrialResult(S.UNAVAILABLE, "当前没有获准的可尝试方案，未改变播放", result)
        return TrialResult(S.UNKNOWN, "暂时无法确认播放结果，未重新发起播放", result)
